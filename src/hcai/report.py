"""Publish measured results into the README and docs/results/.

Every number comes from files that `train`, `stability`, `eval` and `compare` wrote under
artifacts/ (project rule: numbers in docs come from artifacts/reports). Nothing is typed by hand.
The README block between the two markers is replaced; the rest of the README is never touched."""

from __future__ import annotations

import json
import shutil
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from hcai import __version__
from hcai.config import Config
from hcai.errors import HcaiError
from hcai.ml.runs import list_runs
from hcai.textio import read_text

START = "<!-- RESULTS:START (generated by `python -m hcai report`; do not edit by hand) -->"
END = "<!-- RESULTS:END -->"
COPY_NAMES = ("model_report.md", "rag_eval.md", "stability.md")
COPY_SUFFIX = (".png",)


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(read_text(path)) if path.is_file() else None


def _ci(x: list[float]) -> str:
    return f"[{x[0]:.2f}, {x[1]:.2f}]"


def _model_block(title: str, m: dict[str, Any]) -> list[str]:
    ds = m.get("dataset", {})
    sel, san, lk = m["selected"], m["sanity"], m.get("leakage", {})
    lines = [
        f"#### {title}",
        f"{ds.get('rows', '?')} rows · train {m['n_train']} / test {m['n_test']} · absent features: "
        f"{', '.join(ds.get('absent_features', [])) or 'none'} · selected model: **{sel}**",
        "",
        "| model | accuracy | precision | recall | F1 | ROC-AUC [95% CI] | CV ROC-AUC (train) |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, t in m["test"].items():
        mt, ci = t["metrics"], t["ci95"]["roc_auc"]
        cv = m["cv"].get(name)
        lines.append(
            f"| {name}{' **(selected)**' if name == sel else ''} | {mt['accuracy']:.3f} | {mt['precision']:.3f} "
            f"| {mt['recall']:.3f} | {mt['f1']:.3f} | {mt['roc_auc']:.3f} {_ci(ci)} "
            f"| {cv['mean']:.3f} ± {cv['std']:.3f} |"
            if cv
            else f"| {name} | | | | | | |"
        )
    nested = m.get("nested_cv_auc")
    if nested:
        lines += [
            "",
            f"Nested-CV ROC-AUC of the tuned winner (train split): {nested['mean']:.3f} ± {nested['std']:.3f}",
        ]
    if lk:
        sf = lk["single_feature_auc_max"]
        lines += [
            "",
            f"Leakage checks: **{san.get('verdict', 'n/a').upper()}** · duplicate test rows "
            f"{lk['duplicates']['n_overlap']} · strongest single feature `{sf['feature']}` AUC {sf['auc']:.2f} · "
            f"label-shuffle AUC {lk['label_shuffle']['mean']:.2f} (chance = 0.5)",
        ]
        lines += [f"- {r}" for r in san.get("reasons", [])]
    return [*lines, ""]


def _stability_block(s: dict[str, Any]) -> list[str]:
    lines = [
        "#### Split stability",
        f"{s['n_splits']} random stratified splits, test n≈{s['n_test']}, default hyper-parameters:",
        "",
        "| model | mean AUC | std | 5th pct | 95th pct | max | splits > ceiling |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {k} | {v['mean']:.3f} | {v['std']:.3f} | {v['p05']:.3f} | {v['p95']:.3f} | {v['max']:.3f} "
        f"| {v['share_above_ceiling']:.0%} |"
        for k, v in s["per_model"].items()
    ]
    return [*lines, ""]


def _rag_block(r: dict[str, Any]) -> list[str]:
    ret, ref, saf, gen = r["retrieval"], r["refusal"], r["safety"], r["generation"]

    def f(x: float | None) -> str:
        return "n/a" if x is None else f"{x:.2f}"

    lines = [
        "#### RAG evaluation (golden set)",
        f"{r['n_items']} items · threshold in use {r['threshold_used']:.3f} "
        f"(false refusal {f(r['current_rates']['false_refusal_rate'])}, false answer {f(r['current_rates']['false_answer_rate'])})",
        "",
        "| metric | value |",
        "|---|---|",
        f"| retrieval hit@1 / hit@3 / hit@5 | {f(ret.get('hit@1'))} / {f(ret.get('hit@3'))} / {f(ret.get('hit@5'))} |",
        f"| retrieval MRR | {f(ret['mrr'])} |",
        f"| refusal precision / recall | {f(ref['precision'])} / {f(ref['recall'])} |",
        f"| false-refusal / false-answer rate | {f(ref['false_refusal_rate'])} / {f(ref['false_answer_rate'])} |",
        f"| emergency recall · false alarms | {f(saf['emergency_recall'])} · {saf['false_alarms']} |",
        f"| answers (LLM / extractive) | {gen['llm_answers']} / {gen['extractive_answers']} |",
        f"| faithfulness proxy (lexical, LLM answers) | {f(gen['faithfulness_proxy_llm'])} |",
        f"| latency p50 / p95 (ms) | {gen['latency_ms'].get('p50', 0):.0f} / {gen['latency_ms'].get('p95', 0):.0f} |",
        f"| behaviour failures | {len(r.get('behaviour_failures', []))} |",
    ]
    if r.get("ablation"):
        lines += ["", "| retrieval variant | hit@1 | hit@3 | MRR |", "|---|---|---|---|"]
        lines += [
            f"| {a['variant']} | {a['hit@1']:.2f} | {a['hit@3']:.2f} | {a['mrr']:.2f} |"
            for a in r["ablation"]
        ]
    return [*lines, ""]


def _runs_block(cfg: Config) -> list[str]:
    runs = list_runs(cfg)
    if not runs:
        return []
    lines = [
        "#### Archived training runs",
        "",
        "| run | build | dataset | model | test ROC-AUC [95% CI] | leakage verdict |",
        "|---|---|---|---|---|---|",
    ]
    for r in runs:
        t = r["test"].get(r["selected"] or "")
        auc = f"{t['roc_auc']:.3f} {_ci(t['roc_auc_ci95'])}" if t else "n/a"
        lines.append(
            f"| {r['run_id']} | {r['build']} | {r['dataset']} | {r['selected'] or '-'} | {auc} | {r['verdict']} |"
        )
    comps = sorted((cfg.paths.artifacts / "reports").glob("comparison_*.json"))
    if comps:
        lines += ["", "Comparisons (full tables in `docs/results/`):"]
        for p in comps:
            c = json.loads(read_text(p))
            lines.append(
                f"- **{c['a']}** vs **{c['b']}**: "
                + " ".join(c["notes"][:1])
                + (
                    " 95% CIs overlap."
                    if c["ci_overlap"]
                    else " 95% CIs do not overlap."
                    if c["ci_overlap"] is False
                    else ""
                )
            )
    return [*lines, ""]


def build_results_block(cfg: Config) -> str:
    reports = cfg.paths.reports_dir
    body: list[str] = []
    m = _load(reports / "metrics.json")
    if m:
        body += _model_block("Primary model (UCI Cleveland)", m)
    k = _load(
        cfg.paths.artifacts / "datasets" / "kaggle_heart_failure" / "reports" / "metrics.json"
    )
    if k:
        body += _model_block("Second dataset (Kaggle Heart Failure Prediction)", k)
    s = _load(reports / "stability.json")
    if s:
        body += _stability_block(s)
    body += _runs_block(cfg)
    r = _load(reports / "rag_eval.json")
    if r:
        body += _rag_block(r)
    if not body:
        raise HcaiError("No results found under artifacts/. Run train / eval first.")
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    head = [
        START,
        f"_Generated {stamp} by hcai {__version__} from `artifacts/`. Test sets are small (Cleveland n≈61): read every number with its CI._",
        "",
    ]
    return "\n".join([*head, *body, END])


def publish(cfg: Config, readme: Path | None = None) -> tuple[Path, list[Path]]:
    """Write docs/results/* copies and replace the README block. Returns (readme, copied files)."""
    root = cfg.paths.artifacts.parent
    readme = readme or root / "README.md"
    if not readme.is_file():
        raise HcaiError(f"README not found: {readme}")
    raw_text = read_text(readme)
    newline = "\r\n" if "\r\n" in raw_text else "\n"  # keep the file's own line endings
    text = raw_text.replace("\r\n", "\n")
    if START not in text or END not in text:
        raise HcaiError(
            f"{readme.name} has no results block. Add these two lines where the results should go:\n"
            f"{START}\n{END}"
        )
    block = build_results_block(cfg)
    out = root / "docs" / "results"
    out.mkdir(parents=True, exist_ok=True)
    copied: list[Path] = []
    sources = [
        cfg.paths.reports_dir,
        cfg.paths.artifacts / "datasets" / "kaggle_heart_failure" / "reports",
    ]
    for src in sources:
        tag = "kaggle_" if "datasets" in src.parts else ""
        for f in sorted(src.glob("*")) if src.is_dir() else []:
            if f.name in COPY_NAMES or f.suffix in COPY_SUFFIX or f.name.startswith("comparison_"):
                dest = out / f"{tag}{f.name}"
                shutil.copyfile(f, dest)
                copied.append(dest)
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    new_text = (head + block + tail).replace("\n", newline)
    readme.write_bytes(new_text.encode("utf-8"))  # bytes: no platform newline translation
    return readme, copied
